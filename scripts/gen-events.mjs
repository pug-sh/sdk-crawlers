import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { isDeepStrictEqual } from 'node:util'

// Builds src/events.generated.ts from the descriptor set of pug's protos (make codegen): the
// procedure a report goes to, and the limits on the two fields it fills from a site's request,
// found through BatchCreate's types. A renamed rpc, or any change to those fields' rules but the
// limits' values, then fails make codegen, not a site's reports.

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const { file: files } = JSON.parse(readFileSync(join(root, '.codegen-tmp/protos.json'), 'utf8'))

const find = (list, name) => {
  const found = list?.find(x => x.name === name)
  if (!found) throw new Error(`no ${name} in the descriptor`)
  return found
}

const messages = new Map()
const index = (scope, types = []) => {
  for (const type of types) {
    messages.set(`${scope}.${type.name}`, type)
    index(`${scope}.${type.name}`, type.nestedType)
  }
}
for (const file of files) index(`.${file.package}`, file.messageType)

const typeOf = (message, name) => {
  const type = messages.get(find(message.field, name).typeName)
  if (!type) throw new Error(`${message.name}.${name} is no longer a message`)
  return type
}

const limit = (message, name, key, kept) => {
  const rules = find(message.field, name).options?.['[buf.validate.field]'] ?? {}
  const { [key]: value, ...string } = rules.string ?? {}
  const n = Number(value)
  if (!Number.isSafeInteger(n) || n <= 0) throw new Error(`no ${key} on ${message.name}.${name} in the descriptor`)
  if (!isDeepStrictEqual({ ...rules, string }, kept)) {
    throw new Error(`${message.name}.${name} has rules the package doesn't keep: ${JSON.stringify(rules)}`)
  }
  return n
}

const events = find(files, 'sdk/events/v1/events.proto')
const service = find(events.service, 'EventsService')
const method = find(service.method, 'BatchCreate')
const qualified = name => `.${events.package}.${name}`
if (method.clientStreaming || method.serverStreaming) throw new Error('BatchCreate is no longer unary')
if (method.inputType !== qualified('BatchCreateRequest') || method.outputType !== qualified('BatchCreateResponse')) {
  throw new Error('BatchCreate no longer takes BatchCreateRequest and returns BatchCreateResponse')
}
const procedure = `/${events.package}.${service.name}/${method.name}`
const event = typeOf(messages.get(method.inputType), 'events')
const property = typeOf(typeOf(event, 'auto_properties'), 'value')
const client = typeOf(event, 'client')
const maxPropertyLength = limit(property, 'string_value', 'maxLen', { string: {} })
const maxUserAgentBytes = limit(client, 'user_agent', 'maxBytes', { required: true, string: { minLen: '1' } })

const out = `// AUTOGENERATED: do not edit. Run \`make codegen\` to regenerate.
// From pug's protos: the procedure a report goes to, the max_len of an auto property's
// string_value, in code points, and the max_bytes of the client's user_agent.

export const procedure = ${JSON.stringify(procedure)}
export const maxPropertyLength = ${maxPropertyLength}
export const maxUserAgentBytes = ${maxUserAgentBytes}
`
writeFileSync(join(root, 'src', 'events.generated.ts'), out)
console.log(`wrote ${procedure}, with limits ${maxPropertyLength} and ${maxUserAgentBytes}`)
