import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

// Builds src/agents.generated.ts from the crawler table's descriptor (make codegen) and the
// crawler-user-agents list. It mirrors pug's internal/crawler: a table row matches by token, and a
// list entry tagged search-engine or seo matches by its pattern unless its name holds a row's
// token, so an impostor spelling such as NotGooglebot never stands in for Googlebot.

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const readJSON = path => JSON.parse(readFileSync(join(root, path), 'utf8'))

const categories = {
  CATEGORY_ANSWERS: 'answers',
  CATEGORY_SEARCH: 'search',
  CATEGORY_TRAINING: 'training',
  CATEGORY_SEO: 'seo',
  CATEGORY_OTHER: 'other',
}

const descriptor = readJSON('.codegen-tmp/protos.json')
const file = descriptor.file.find(f => f.name === 'common/crawlers/v1/crawlers.proto')
const crawlerEnum = file?.enumType?.find(e => e.name === 'Crawler')
if (!crawlerEnum) throw new Error('no Crawler enum in the descriptor')

const option = (value, name) => value.options?.[`[common.crawlers.v1.${name}]`]
const table = []
for (const value of crawlerEnum.value) {
  if (value.number === 0 || value.options?.deprecated) continue
  const tokens = option(value, 'token') ?? []
  const category = categories[option(value, 'category')]
  if (tokens.length === 0 || !category) throw new Error(`${value.name} has no token or category`)
  table.push([tokens[0], category, ...tokens.map(t => t.toLowerCase())])
}
const tokens = table.flatMap(([, , ...t]) => t)

// The name pug records for a list entry: its pattern matched against its own example user agent,
// as internal/botdetect derives it.
const trim = s => s.replace(/^[^\p{L}\p{Nd}]+|[^\p{L}\p{Nd}]+$/gu, '')
const nameOf = entry => {
  const re = new RegExp(entry.pattern)
  for (const ua of entry.instances ?? []) {
    const name = trim(re.exec(ua)?.[0] ?? '')
    if (name) return name
  }
  return trim(entry.pattern.replace(/[\\^$()]/g, ''))
}

const list = readJSON('node_modules/crawler-user-agents/crawler-user-agents.json')
const { version } = readJSON('node_modules/crawler-user-agents/package.json')
const license = readFileSync(join(root, 'node_modules/crawler-user-agents/LICENSE'), 'utf8')
  .trim()
  .split('\n')
  .map(line => `//${line ? ` ${line}` : ''}`)
  .join('\n')
const listed = []
for (const entry of list) {
  const tags = entry.tags ?? []
  const category = tags.includes('search-engine') ? 'search' : tags.includes('seo') ? 'seo' : undefined
  if (!category) continue
  const name = nameOf(entry)
  if (tokens.some(t => name.toLowerCase().includes(t))) continue
  listed.push([name, category, entry.pattern])
}

const lines = rows => rows.map(r => `  [${r.map(v => JSON.stringify(v)).join(', ')}],`).join('\n')
const out = `// AUTOGENERATED: do not edit. Run \`make codegen\` to regenerate.
// table: pug's crawler table (proto/common/crawlers/v1), as [name, category, ...lowercased tokens].
// listed: crawler-user-agents@${version}, its search-engine and seo entries, as [name, category, pattern],
// under its license:
//
${license}

import type { Category } from './match.js'

export const table: readonly (readonly [string, Category, ...string[]])[] = [
${lines(table)}
]

export const listed: readonly (readonly [string, Category, string])[] = [
${lines(listed)}
]
`
writeFileSync(join(root, 'src', 'agents.generated.ts'), out)
console.log(`wrote ${table.length} table agents and ${listed.length} list entries`)
